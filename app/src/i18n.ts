export type TextKey = keyof typeof he;

/** An item's name or its one-line effect, by item id (the words are in the table above). */
export function itemText(id: string, part: "name" | "desc"): string {
  return (he as Record<string, string>)[`item_${id}_${part}`] ?? extraItemText[`${id}:${part}`] ?? id;
}

/** Names the data carries itself (game/economy.json: name_he, desc_he), added when the economy is read. */
const extraItemText: Record<string, string> = {};
export function addItemText(id: string, name: string, desc: string): void {
  extraItemText[`${id}:name`] = name;
  extraItemText[`${id}:desc`] = desc;
}

export function t(key: TextKey, values: Record<string, string | number> = {}): string {
  return he[key].replace(/\{(\w+)\}/g, (_, k: string) => String(values[k] ?? `{${k}}`));
}
