#: Mods in load order: a later mod wins over an earlier one.
MOD_ORDER = ("tuxemon", "nagmon")


def mod_file(rel: str) -> Path | None:
    """The file a mod-aware Tuxemon would load for ``rel`` (nagmon wins)."""
    for mod in reversed(MOD_ORDER):
        path = MODS / mod / rel
        if path.is_file():
            return path
    return None


def rel_repo(path: Path) -> str:
    return path.resolve().relative_to(REPO).as_posix()


def json_bytes(obj: Any, *, compact: bool = False) -> bytes:
    if compact:
        text = json.dumps(obj, ensure_ascii=False, separators=(",", ":"))
    else:
        text = json.dumps(obj, ensure_ascii=False, indent=1)
    return (text + "\n").encode("utf-8")


def png_bytes(image: Image.Image) -> bytes:
    """
    The PNG of ``image``, the smaller of two lossless encodings: as it
    is, and (with at most 256 colours) as a palette with per-entry alpha.
    """
    candidates = [_encode(image)]
    palette = palette_image(image)
    if palette is not None:
        candidates.append(_encode(palette))
    return min(candidates, key=len)


def _encode(image: Image.Image) -> bytes:
    buf = io.BytesIO()
    params: dict[str, Any] = {"optimize": True}
    if image.mode == "P" and "transparency" in image.info:
        params["transparency"] = image.info["transparency"]
    image.save(buf, format="PNG", **params)
    return buf.getvalue()


def palette_image(image: Image.Image) -> Image.Image | None:
    """
    ``image`` as a palette picture with exactly the same RGBA pixels,
    or None when it has more than 256 colours. The palette is sorted,
    so the same pixels always give the same bytes.
    """
    if image.mode != "RGBA":
        return None
    if image.getcolors(256) is None:
        return None
    # One big-endian uint32 per pixel (R, G, B, A from the top byte): it
    # sorts like the (r, g, b, a) tuples, and np.unique on it is fast.
    rgba = np.ascontiguousarray(np.asarray(image, dtype=np.uint8))
    keys = rgba.view(">u4").ravel()
    values, index = np.unique(keys, return_inverse=True)
    palette = values.astype(">u4").view(np.uint8).reshape(-1, 4)
    out = Image.fromarray(
        index.reshape(image.height, image.width).astype(np.uint8), "P"
    )
    out.putpalette(palette[:, :3].tobytes())
    alphas = palette[:, 3].tobytes()
    if any(a != 255 for a in alphas):
        out.info["transparency"] = alphas
    return out


@dataclass
class Asset:
    """Where a shipped file came from, for credits.json."""

    path: str
    sources: list[str]
    kind: str
    note: str = ""
    #: How the picture was changed, for its licence: "xBRZ x4" (an
    #: upscale by tools/app/hd.py), or "" for a picture as it is.
    adapted: str = ""


@dataclass
class Output:
    """The files of one build, by path relative to ``app/public/game``."""

    #: Generated bytes (JSON, text).
    data: dict[str, bytes] = field(default_factory=dict)
    #: Generated images; compared by pixels, not by encoder bytes.
    images: dict[str, Image.Image] = field(default_factory=dict)
    #: Files copied as they are.
    copies: dict[str, Path] = field(default_factory=dict)
    #: Credits bookkeeping for every shipped asset (not for JSON data).
    assets: dict[str, Asset] = field(default_factory=dict)
    #: Messages for the report (things that could not be converted...).
    notes: list[str] = field(default_factory=list)

    def _claim(self, rel: str) -> None:
        if rel in self.data or rel in self.images or rel in self.copies:
            raise ValueError(f"{rel}: written twice")

    def add_json(self, rel: str, obj: Any, *, compact: bool = False) -> None:
        self._claim(rel)
        self.data[rel] = json_bytes(obj, compact=compact)

    def add_image(
        self,
        rel: str,
        image: Image.Image,
        sources: Iterable[Path],
        kind: str,
        *,
        adapted: str = "",
    ) -> None:
        self._claim(rel)
        self.images[rel] = image
        self.assets[rel] = Asset(
            rel, sorted({rel_repo(p) for p in sources}), kind, adapted=adapted
        )

    def add_copy(
        self, rel: str, src: Path, kind: str, *, note: str = ""
    ) -> None:
        if rel in self.copies and self.copies[rel] == src:
            return
        self._claim(rel)
        if not src.is_file():
            raise FileNotFoundError(src)
        self.copies[rel] = src
        self.assets[rel] = Asset(rel, [rel_repo(src)], kind, note)

    def paths(self) -> set[str]:
        return set(self.data) | set(self.images) | set(self.copies)

    # ------------------------------------------------------------ writing
    def write(self, root: Path) -> None:
        root.mkdir(parents=True, exist_ok=True)
        wanted = self.paths()
        for existing in _files(root):
            if existing not in wanted:
                (root / existing).unlink()
        for rel, data in self.data.items():
            _write_if_changed(root / rel, data)
        for rel, image in self.images.items():
            target = root / rel
            if target.is_file() and _same_pixels(target, image):
                continue
            _write_if_changed(target, png_bytes(image))
        for rel, src in self.copies.items():
            _write_if_changed(root / rel, src.read_bytes())
        _remove_empty_dirs(root)

    # ----------------------------------------------------------- checking
    def differences(self, root: Path) -> list[str]:
        """What differs between this build and the files under ``root``."""
        problems: list[str] = []
        have = set(_files(root)) if root.is_dir() else set()
        wanted = self.paths()
        problems += [f"missing: {p}" for p in sorted(wanted - have)]
        problems += [f"not built any more: {p}" for p in sorted(have - wanted)]
        for rel in sorted(wanted & have):
            target = root / rel
            if rel in self.data:
                same = target.read_bytes() == self.data[rel]
            elif rel in self.images:
                same = _same_pixels(target, self.images[rel])
            else:
                same = _digest(target) == _digest(self.copies[rel])
            if not same:
                problems.append(f"changed: {rel}")
        return problems


def _files(root: Path) -> list[str]:
    return sorted(
        p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file()
    )


def _write_if_changed(target: Path, data: bytes) -> None:
    if target.is_file() and target.read_bytes() == data:
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    tmp = target.with_name(target.name + ".tmp")
    tmp.write_bytes(data)
    os.replace(tmp, target)


def _remove_empty_dirs(root: Path) -> None:
    for d in sorted(root.rglob("*"), key=lambda p: -len(p.parts)):
        if d.is_dir() and not any(d.iterdir()):
            d.rmdir()


def _digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _same_pixels(path: Path, image: Image.Image) -> bool:
    """The file shows the same pixels (it may be stored as a palette)."""
    try:
        with Image.open(path) as old:
            old.load()
            if old.size != image.size:
                return False
            if old.mode == image.mode and old.tobytes() == image.tobytes():
                return True
            return _rgba(old) == _rgba(image)
    except OSError:
        return False


def _rgba(image: Image.Image) -> bytes:
    return image.convert("RGBA").tobytes()
